#!/usr/bin/env python3
"""Compute per-sector median benchmarks for the key metrics and write them to
backend/sector_benchmarks.py.

Sector-relative scoring needs a reference point: a 13% ROIC is elite for a
utility but mediocre for software. This bakes the sector medians (of investable
quality names) into a table the app reads. Regenerate periodically — multiples
drift — the same way the universe is refreshed.

    .venv/bin/python tools/compute_sector_benchmarks.py            # 'full' universe
    .venv/bin/python tools/compute_sector_benchmarks.py --scope large
"""
from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from data import fetch_stock                                   # noqa: E402
from valuation import compute_metrics, resolve_assumptions     # noqa: E402
import universe as _universe                                   # noqa: E402

METRICS = ["roic", "roe", "net_margin", "gross_margin", "revenue_cagr",
           "trailing_pe", "price_to_fcf", "ev_to_ebitda"]
MULTIPLES = {"trailing_pe", "price_to_fcf", "ev_to_ebitda"}


def _extract(m):
    return {
        "roic": m["returns"].get("roic_avg") or m["returns"].get("roic_latest"),
        "roe": m["returns"].get("roe_avg") or m["returns"].get("roe_latest"),
        "net_margin": m["margins"]["net"].get("avg"),
        "gross_margin": m["margins"]["gross"].get("avg"),
        "revenue_cagr": m["growth"].get("revenue_cagr"),
        "trailing_pe": m["multiples"].get("trailing_pe"),
        "price_to_fcf": m["multiples"].get("price_to_fcf"),
        "ev_to_ebitda": m["due_diligence"].get("ev_to_ebitda"),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scope", default="full")
    args = ap.parse_args()
    a = resolve_assumptions()
    syms = _universe.get(args.scope)
    print(f"Computing sector benchmarks from {len(syms)} names ({args.scope})…")
    by_sector: dict[str, list] = {}
    for i, s in enumerate(syms, 1):
        try:
            stk = fetch_stock(s, use_edgar=False)   # Yahoo, fast
            if stk.get("error"):
                continue
            sec = stk["info"].get("sector")
            if not sec:
                continue
            by_sector.setdefault(sec, []).append(_extract(compute_metrics(stk, a)))
            if i % 20 == 0:
                print(f"  [{i}/{len(syms)}]")
        except Exception:  # noqa: BLE001
            continue

    table: dict[str, dict] = {}
    for sec, rows in by_sector.items():
        if len(rows) < 4:
            continue
        entry = {"n": len(rows)}
        for k in METRICS:
            xs = [r[k] for r in rows if r[k] is not None]
            if k in MULTIPLES:
                xs = [x for x in xs if 0 < x < 200]
            if len(xs) >= 3:
                entry[k] = round(statistics.median(xs), 4)
        table[sec] = entry

    out = ROOT / "backend" / "sector_benchmarks.py"
    lines = ['"""Per-sector median benchmarks — GENERATED by',
             'tools/compute_sector_benchmarks.py. Regenerate periodically.',
             '',
             'Used for sector-relative scoring: is this ROIC / margin / multiple good',
             '*for this sector*? A 13% ROIC is elite for a utility, mediocre for software.',
             '"""', '', 'from typing import Any, Optional', '',
             f'GENERATED_FROM = "{args.scope} universe, {sum(len(v) for v in by_sector.values())} names"',
             '', 'BENCHMARKS: dict[str, dict[str, float]] = {']
    for sec in sorted(table):
        lines.append(f"    {sec!r}: {table[sec]!r},")
    lines.append("}")
    lines.append("")
    lines.append(_HELPERS)
    out.write_text("\n".join(lines))
    print(f"\nWrote {out} with {len(table)} sectors.")
    for sec in sorted(table):
        print(f"  {sec:24} n={table[sec]['n']:3}  ROIC {table[sec].get('roic', 0)*100:.0f}%  "
              f"net-margin {table[sec].get('net_margin', 0)*100:.0f}%  P/E {table[sec].get('trailing_pe', 0):.0f}")


_HELPERS = '''

# Metrics where HIGHER is better vs the sector (quality/growth) vs where LOWER is
# better (valuation multiples — cheaper than the sector is good).
_HIGHER_BETTER = {"roic", "roe", "net_margin", "gross_margin", "revenue_cagr"}
_LOWER_BETTER = {"trailing_pe", "price_to_fcf", "ev_to_ebitda"}


def sector_median(sector: Optional[str], metric: str) -> Optional[float]:
    return (BENCHMARKS.get(sector or "") or {}).get(metric)


def compare(sector: Optional[str], metric: str, value: Optional[float]) -> Optional[dict[str, Any]]:
    """Where does `value` sit vs the sector median? Returns {median, ratio, verdict}
    with verdict in {well_above, above, inline, below, well_below} oriented so that
    'above' always means BETTER (cheaper multiple counts as above)."""
    med = sector_median(sector, metric)
    if med is None or value is None or med == 0:
        return None
    ratio = value / med
    if metric in _LOWER_BETTER:
        ratio = 1 / ratio if ratio else None  # cheaper than sector -> ratio > 1 (better)
    if ratio is None:
        return None
    if ratio >= 1.4:
        verdict = "well_above"
    elif ratio >= 1.1:
        verdict = "above"
    elif ratio >= 0.9:
        verdict = "inline"
    elif ratio >= 0.7:
        verdict = "below"
    else:
        verdict = "well_below"
    return {"median": med, "value": value, "ratio": round(ratio, 2), "verdict": verdict}
'''


if __name__ == "__main__":
    main()
